/**
 * Invariant: the Agent Server keeps ONE parameters schema per client-tool name
 * for the whole process (first registration wins) and re-registers the stored
 * client tools of every conversation it resumes. Changing the schema of
 * CANVAS_UI_CLIENT_TOOL therefore requires bumping the version suffix below
 * and appending the previous name to CANVAS_UI_TOOL_NAMES, so saved
 * conversations keep rendering and dispatching UI commands.
 */
export const LEGACY_CANVAS_UI_TOOL_NAME = "canvas_ui";
/** v1 client tool (no `open_url` / `webview` / `url`); only seen in old events. */
export const CANVAS_UI_CLIENT_TOOL_NAME_V1 = "canvas_ui_control";
/** The name registered for new conversations. */
export const CANVAS_UI_CLIENT_TOOL_NAME = "canvas_ui_control_v2";

/** Every Canvas UI tool name that may appear in events, oldest first. */
export const CANVAS_UI_TOOL_NAMES = [
  LEGACY_CANVAS_UI_TOOL_NAME,
  CANVAS_UI_CLIENT_TOOL_NAME_V1,
  CANVAS_UI_CLIENT_TOOL_NAME,
] as const;

/**
 * Action discriminator generated by the SDK for the client-defined Canvas UI
 * tool (`ClientAction_<tool-name>`). Keep the SDK naming convention contained
 * here instead of repeating its generated class name throughout the frontend.
 */
export const CANVAS_UI_CLIENT_ACTION_KIND =
  `ClientAction_${CANVAS_UI_CLIENT_TOOL_NAME}` as const;
export const CANVAS_UI_CLIENT_ACTION_KIND_V1 =
  `ClientAction_${CANVAS_UI_CLIENT_TOOL_NAME_V1}` as const;

/** Client action kinds (current and historical) that carry Canvas UI commands. */
export const CANVAS_UI_CLIENT_ACTION_KINDS = [
  CANVAS_UI_CLIENT_ACTION_KIND_V1,
  CANVAS_UI_CLIENT_ACTION_KIND,
] as const;

const CANVAS_UI_TOOL_NAME_SET: ReadonlySet<string> = new Set(
  CANVAS_UI_TOOL_NAMES,
);
const CANVAS_UI_CLIENT_TOOL_NAME_SET: ReadonlySet<string> = new Set([
  CANVAS_UI_CLIENT_TOOL_NAME_V1,
  CANVAS_UI_CLIENT_TOOL_NAME,
]);
const CANVAS_UI_ACTION_KIND_SET: ReadonlySet<string> = new Set([
  "CanvasUIAction",
  ...CANVAS_UI_CLIENT_ACTION_KINDS,
]);

/** True for the legacy Python tool and every client tool version. */
export const isCanvasUiToolName = (name: string | null | undefined): boolean =>
  !!name && CANVAS_UI_TOOL_NAME_SET.has(name);

/** True for client tool versions only (events of kind ClientToolObservation). */
export const isCanvasUiClientToolName = (
  name: string | null | undefined,
): boolean => !!name && CANVAS_UI_CLIENT_TOOL_NAME_SET.has(name);

/** True for the legacy `CanvasUIAction` kind and every client action kind. */
export const isCanvasUiActionKind = (
  kind: string | null | undefined,
): boolean => !!kind && CANVAS_UI_ACTION_KIND_SET.has(kind);
