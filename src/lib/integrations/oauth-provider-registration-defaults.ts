export const getOAuthProviderRegistrationDefaults = (slug: string) => {
  const defaults = registrationDefaults[slug];
  if (!defaults) {
    return undefined;
  }

  return {
    ...defaults,
    serverUrl:
      defaults.provider === "http"
        ? defaults.serverUrl
        : defaults.serverUrl ?? buildManagedMcpServerUrl(slug),
  };
};
