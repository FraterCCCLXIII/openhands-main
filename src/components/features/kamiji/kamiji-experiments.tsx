/* eslint-disable i18next/no-literal-string -- dev-only prototype, not product copy */
import React from "react";
import { ExternalLink } from "lucide-react";
import { cn } from "#/utils/utils";

interface Experiment {
  id: string;
  label: string;
  date: string;
  description: string;
}

const EXPERIMENTS: Experiment[] = [
  {
    id: "chatty-face-plugin",
    label: "Chatty face",
    date: "May 2025",
    description:
      "The first talking head: a themed 2D face with a rig editor, voice in and out (the chat backend is not wired up here).",
  },
  {
    id: "kamiji-rig",
    label: "Face rig",
    date: "2 Jun 2025",
    description:
      "A standalone 2D SVG face rig with expressions, animations and themes.",
  },
  {
    id: "kamiji-game",
    label: "Pet game",
    date: "2 Jun 2025",
    description:
      "A Tamagotchi-style pet game with an RPG map, generated by a Lovable bot.",
  },
  {
    id: "kamiji-demo",
    label: "Device demo",
    date: "9-12 Jun 2025",
    description:
      "A Tamagotchi device UI built for Electron, shown here as its web build.",
  },
];

const FRAME_HEIGHT_CLASS = "h-160";

function experimentUrl(id: string) {
  return `/kamiji-experiments/${id}/index.html`;
}

export function KamijiExperiments() {
  const [activeId, setActiveId] = React.useState(EXPERIMENTS[0].id);
  const active = EXPERIMENTS.find((e) => e.id === activeId) ?? EXPERIMENTS[0];

  return (
    <section className="flex w-full flex-col gap-3">
      <h2 className="text-lg font-semibold text-foreground">
        Earlier experiments
      </h2>
      <p className="text-sm text-muted">
        Prototypes from before the 3D library, loaded as static builds. They are
        unpolished; kamiji-game was generated by a Lovable bot.
      </p>
      <div
        role="tablist"
        aria-label="Earlier experiments"
        className="flex flex-wrap gap-2"
      >
        {EXPERIMENTS.map((e) => (
          <button
            key={e.id}
            type="button"
            role="tab"
            id={`kamiji-exp-tab-${e.id}`}
            aria-selected={e.id === activeId}
            aria-controls="kamiji-exp-panel"
            onClick={() => setActiveId(e.id)}
            className={cn(
              "rounded-full border border-border px-3 py-1 text-sm",
              e.id === activeId
                ? "bg-primary/15 text-primary"
                : "bg-surface text-muted hover:text-foreground",
            )}
          >
            {e.label}
          </button>
        ))}
      </div>
      <div
        role="tabpanel"
        id="kamiji-exp-panel"
        aria-labelledby={`kamiji-exp-tab-${active.id}`}
        className="flex flex-col gap-2"
      >
        <div className="flex flex-wrap items-center justify-between gap-2">
          <p className="text-sm text-muted">
            <span className="font-medium text-foreground">{active.date}.</span>{" "}
            {active.description}
          </p>
          <a
            href={experimentUrl(active.id)}
            target="_blank"
            rel="noreferrer"
            className="inline-flex items-center gap-1 text-sm text-primary hover:underline"
          >
            Open in new tab <ExternalLink size={14} />
          </a>
        </div>
        <iframe
          key={active.id}
          title={`Kamiji experiment: ${active.label}`}
          src={experimentUrl(active.id)}
          sandbox="allow-scripts allow-same-origin"
          loading="lazy"
          className={cn(
            "w-full rounded-2xl border border-border bg-surface",
            FRAME_HEIGHT_CLASS,
          )}
        />
      </div>
    </section>
  );
}
