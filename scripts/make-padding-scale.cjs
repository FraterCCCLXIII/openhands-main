// Generates src/padding-scale.generated.css: one unlayered override per
// numeric Tailwind padding utility used under src/, multiplying its value by
// --oh-padding-scale (set by the appearance menu's Padding slider). Unlayered
// rules beat Tailwind's layered utilities, so every padded surface follows the
// slider, including modals. Re-run after adding a padding class.
const fs = require("node:fs");
const path = require("node:path");

const SRC = path.join(__dirname, "..", "src");
const OUT = path.join(SRC, "padding-scale.generated.css");
const BREAKPOINTS = [
  ["sm", "40rem"],
  ["md", "48rem"],
  ["lg", "64rem"],
  ["xl", "80rem"],
  ["2xl", "96rem"],
];
const PROPERTY = {
  p: "padding",
  px: "padding-inline",
  py: "padding-block",
  pt: "padding-top",
  pr: "padding-right",
  pb: "padding-bottom",
  pl: "padding-left",
};
const TOKEN =
  /(?<![\w:[-])(?:(sm|md|lg|xl|2xl):)?(px|py|pt|pr|pb|pl|p)-(\d+(?:\.\d+)?)(?![\w.[-])/g;

function walk(dir, files = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, files);
    else if (/\.(tsx?|jsx?)$/.test(entry.name) && !/\.test\./.test(entry.name))
      files.push(full);
  }
  return files;
}

const used = new Map(); // breakpoint ("" for base) -> Set("prefix-value")
for (const file of walk(SRC)) {
  const text = fs.readFileSync(file, "utf8");
  for (const [, bp = "", prefix, value] of text.matchAll(TOKEN)) {
    if (!used.has(bp)) used.set(bp, new Set());
    used.get(bp).add(`${prefix}-${value}`);
  }
}

const rule = (bp, key) => {
  const [prefix, value] = [
    key.slice(0, key.indexOf("-")),
    key.slice(key.indexOf("-") + 1),
  ];
  const selector = `.${bp ? `${bp}\\:` : ""}${prefix}-${value.replace(".", "\\.")}`;
  return `${selector}{${PROPERTY[prefix]}:calc(var(--spacing)*${value}*var(--oh-padding-scale,1))}`;
};
// Tailwind's own order: shorthand first, then axes, then single sides, so
// `p-4 px-2` and `px-4 pt-2` keep resolving the way they do without overrides.
const ORDER = ["p", "px", "py", "pt", "pr", "pb", "pl"];
const parse = (key) => [
  ORDER.indexOf(key.slice(0, key.indexOf("-"))),
  Number(key.slice(key.indexOf("-") + 1)),
];
const sorted = (set) =>
  [...(set ?? [])].sort((a, b) => {
    const [ai, an] = parse(a);
    const [bi, bn] = parse(b);
    return ai - bi || an - bn;
  });

const chunks = [
  "/* Generated by scripts/make-padding-scale.cjs — do not edit. */",
  ...sorted(used.get("")).map((key) => rule("", key)),
];
for (const [bp, min] of BREAKPOINTS) {
  const keys = sorted(used.get(bp));
  if (keys.length === 0) continue;
  chunks.push(
    `@media (min-width:${min}){\n${keys.map((key) => rule(bp, key)).join("\n")}\n}`,
  );
}
fs.writeFileSync(OUT, `${chunks.join("\n")}\n`);
console.log(`Wrote ${path.relative(process.cwd(), OUT)}`);
