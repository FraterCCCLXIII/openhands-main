function loadStorage(win) {
  try { const v = JSON.parse(win.localStorage.getItem(STORAGE_KEY) || "{}"); return v && typeof v === "object" ? v : {}; } catch { return {}; }
}
function saveStorage(win, value) {
  try { win.localStorage.setItem(STORAGE_KEY, JSON.stringify(value)); } catch { /* storage unavailable */ }
}

function el(doc, tag, props = {}, ...children) {
  const node = doc.createElement(tag);
  for (const [k, v] of Object.entries(props)) {
    if (k === "class") node.className = v;
    else if (k === "text") node.textContent = v;
    else if (k.startsWith("on")) node.addEventListener(k.slice(2), v);
    else if (v !== false && v != null) node.setAttribute(k, v === true ? "" : v);
  }
  for (const c of children) if (c) node.append(c);
  return node;
}

const STATUS_LABEL = { ready: "Playable", external: "Opens in tab", "coming-soon": "Coming soon" };

export function mount(container, games = GAMES) {
  const doc = container.ownerDocument;
  const win = doc.defaultView;
  const stored = loadStorage(win);
  const firstPlayable = games.find((g) => g.status === "ready") || games[0];
  let selectedId = games.some((g) => g.id === stored.lastPlayed) ? stored.lastPlayed : firstPlayable.id;

  const style = el(doc, "style", { text: CSS });
  const root = el(doc, "div", { class: "ar" });
  container.append(style, root);

  function select(id) {
    selectedId = id;
    const g = games.find((x) => x.id === id);
    if (g && g.status !== "coming-soon") saveStorage(win, { ...loadStorage(win), lastPlayed: id });
    render();
  }

  function renderList() {
    const list = el(doc, "ul", { class: "list" });
    for (const g of games) {
      const btn = el(doc, "button", { class: "game", type: "button", "data-game": g.id, "aria-pressed": String(g.id === selectedId), onclick: () => select(g.id) },
        el(doc, "span", { class: "tile", "aria-hidden": "true", text: g.title.charAt(0).toUpperCase() }),
        el(doc, "span", {},
          el(doc, "span", { class: "name" }, el(doc, "span", { text: g.title }), el(doc, "span", { class: "badge", text: STATUS_LABEL[g.status] || g.status })),
          el(doc, "span", { class: "desc", text: g.description }),
        ),
      );
      list.append(el(doc, "li", {}, btn));
    }
    return list;
  }

  function renderMain() {
    const g = games.find((x) => x.id === selectedId) || firstPlayable;
    const main = el(doc, "section", { class: "main", "aria-label": g.title });
    const bar = el(doc, "div", { class: "bar" }, el(doc, "span", { class: "title", text: g.title }));
    const stage = el(doc, "div", { class: "stage" });
    const hasUrl = Boolean(g.url);

    if (g.status === "ready" && hasUrl) {
      const loading = el(doc, "div", { class: "loading", role: "status", text: "Loading game..." });
      const frame = el(doc, "iframe", { title: g.title, sandbox: SANDBOX, allow: ALLOW, allowfullscreen: true, referrerpolicy: "no-referrer", src: g.url });
      frame.addEventListener("load", () => { loading.hidden = true; });
      const showLoading = () => { loading.hidden = false; };
      bar.append(
        el(doc, "button", { class: "btn primary", type: "button", "data-action": "play", onclick: () => frame.focus() , text: "Play" }),
        el(doc, "button", { class: "btn", type: "button", "data-action": "fullscreen", onclick: () => { if (frame.requestFullscreen) frame.requestFullscreen().catch(() => {}); }, text: "Fullscreen" }),
        el(doc, "button", { class: "btn", type: "button", "data-action": "reload", onclick: () => {
          showLoading();
          try { frame.contentWindow.location.reload(); } catch { frame.src = g.url; }
        }, text: "Reload" }),
        el(doc, "a", { class: "btn", "data-action": "open", href: g.url, target: "_blank", rel: "noopener noreferrer", text: "Open in new tab" }),
      );
      stage.append(frame, loading);
    } else if (g.status === "external" && hasUrl) {
      bar.append(el(doc, "a", { class: "btn primary", "data-action": "open", href: g.url, target: "_blank", rel: "noopener noreferrer", text: "Open in new tab" }));
      stage.append(el(doc, "div", { class: "notice" }, el(doc, "strong", { text: g.title }), el(doc, "p", { text: g.note })));
    } else {
      stage.append(el(doc, "div", { class: "notice" }, el(doc, "strong", { text: `${g.title}: coming soon` }), el(doc, "p", { text: g.note })));
    }
    main.append(bar, stage);
    return main;
  }

  function render() {
    root.replaceChildren(
      el(doc, "nav", { "aria-label": "Games" }, el(doc, "h1", { text: "Arcade" }), renderList()),
      renderMain(),
    );
  }

  render();
  return () => { root.remove(); style.remove(); };
}

export function activate(host) {
  return host.registerPage("arcade", ({ container }) => mount(container));
}
