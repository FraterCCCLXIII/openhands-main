// Rebuilds the model price table in extension.js from LiteLLM's public price file.
//   node update-prices.mjs [path-to-model_prices_and_context_window.json]
// Without a path it downloads the file. Only first-party chat models are kept.
// Our own rows (kosmos-engine prices.json) stay in extension.js and take priority.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const URL_ = "https://raw.githubusercontent.com/BerriAI/litellm/main/model_prices_and_context_window.json";
const PROVIDERS = { anthropic: "Anthropic", openai: "OpenAI", gemini: "Google", deepseek: "DeepSeek", xai: "xAI", mistral: "Mistral" };
const SKIP = /(^ft:|audio|realtime|search-preview|transcribe|tts|image|embed|moderation|computer-use|sora|dall|whisper|live|robotics|vision-preview|-latest-\d)/i;
const today = new Date().toISOString().slice(0, 10);

const path = process.argv[2];
const data = path ? JSON.parse(readFileSync(path, "utf8")) : await (await fetch(URL_)).json();
const per = (v) => (typeof v === "number" ? Math.round(v * 1e6 * 10000) / 10000 : null);

const rows = [];
for (const [key, v] of Object.entries(data)) {
  if (!v || typeof v !== "object" || !PROVIDERS[v.litellm_provider]) continue;
  if (!["chat", "responses"].includes(v.mode)) continue;
  const id = key.replace(/^(gemini|deepseek|xai|mistral)\//, "");
  if (SKIP.test(id) || v.input_cost_per_token == null || v.output_cost_per_token == null) continue;
  if (v.deprecation_date && v.deprecation_date < today) continue;
  const long = v.input_cost_per_token_above_200k_tokens != null ? 200000 : v.input_cost_per_token_above_128k_tokens != null ? 128000 : null;
  const sfx = long === 200000 ? "above_200k_tokens" : "above_128k_tokens";
  rows.push([
    id, PROVIDERS[v.litellm_provider], per(v.input_cost_per_token), per(v.output_cost_per_token),
    per(v.cache_read_input_token_cost), per(v.cache_creation_input_token_cost), v.max_input_tokens ?? null,
    long, long ? per(v[`input_cost_per_token_${sfx}`]) : null, long ? per(v[`output_cost_per_token_${sfx}`]) : null,
  ]);
}
// Drop a dated copy when its undated alias has the same prices.
const key = (r) => JSON.stringify(r.slice(2, 6));
const alias = new Map(rows.filter((r) => !/-\d{8}$|-\d{4}-\d{2}-\d{2}$/.test(r[0])).map((r) => [r[0], key(r)]));
const kept = rows.filter((r) => {
  const base = r[0].replace(/-\d{8}$|-\d{4}-\d{2}-\d{2}$/, "");
  return base === r[0] || alias.get(base) !== key(r);
}).sort((a, b) => a[1].localeCompare(b[1]) || a[0].localeCompare(b[0]));

const here = dirname(fileURLToPath(import.meta.url));
const file = join(here, "extension.js");
const src = readFileSync(file, "utf8");
const block = `// PRICES:BEGIN (generated by update-prices.mjs)
// LiteLLM model_prices_and_context_window.json, fetched ${today}. USD per million tokens.
// [id, provider, input, output, cacheRead, cacheWrite, context, longOver, longInput, longOutput]
export const LITELLM_AS_OF = "${today}";
const LITELLM_ROWS = ${JSON.stringify(kept)};
// PRICES:END`;
const out = src.replace(/\/\/ PRICES:BEGIN[\s\S]*?\/\/ PRICES:END/, block);
if (out === src && !src.includes("PRICES:BEGIN")) throw new Error("PRICES markers not found in extension.js");
writeFileSync(file, out);
console.log(`Wrote ${kept.length} models.`);
