#!/usr/bin/env node
// Embeds docs/*.md into extension.js (which must stay one self-contained file).
// Usage: node scripts/embed-docs.mjs   (also: npm run embed-docs)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

// The one place that defines page order and titles. `file` is relative to docs/.
export const PAGES = [
  { id: "index", file: "index.md", title: "Holons documentation" },
  { id: "about", file: "about-this-implementation.md", title: "About this implementation" },
  { id: "how-it-works", file: "how-it-works.md", title: "How it works" },
  { id: "getting-started", file: "getting-started-with-others.md", title: "Getting started with others" },
];

const START = "// <docs:generated>";
const END = "// </docs:generated>";

export function buildBlock(docsDir = join(root, "docs")) {
  const pages = PAGES.map((p) => ({ id: p.id, title: p.title, markdown: readFileSync(join(docsDir, p.file), "utf8").replace(/\r\n?/g, "\n") }));
  const body = pages.map((p) => `  { id: ${JSON.stringify(p.id)}, title: ${JSON.stringify(p.title)}, markdown: ${JSON.stringify(p.markdown)} },`).join("\n");
  return `${START}\n// Generated by scripts/embed-docs.mjs from docs/*.md. Do not edit by hand; run \`npm run embed-docs\`.\nexport const DOCS = [\n${body}\n];\n${END}`;
}

export function embed(source, block) {
  const a = source.indexOf(START);
  const b = source.indexOf(END);
  if (a < 0 || b < a) throw new Error(`extension.js must contain ${START} and ${END}`);
  return source.slice(0, a) + block + source.slice(b + END.length);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const file = join(root, "extension.js");
  const before = readFileSync(file, "utf8");
  const after = embed(before, buildBlock());
  if (after !== before) writeFileSync(file, after);
  console.log(after === before ? "DOCS already up to date" : `Embedded ${PAGES.length} pages into extension.js`);
}
